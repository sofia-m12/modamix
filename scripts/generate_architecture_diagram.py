#!/usr/bin/env python3
"""Generate the repository's structural Mermaid architecture diagram."""

from __future__ import annotations

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "architecture.mmd"
MARKDOWN_OUTPUT = ROOT / "docs" / "architecture-diagram.md"


def python_modules(directory: Path) -> list[str]:
    if not directory.is_dir():
        return []
    return [path.stem for path in sorted(directory.glob("*.py")) if path.name != "__init__.py"]


def typescript_modules(directory: Path) -> list[str]:
    if not directory.is_dir():
        return []
    paths = sorted((*directory.glob("*.ts"), *directory.glob("*.tsx")))
    return [path.stem for path in paths if not path.name.endswith(".d.ts")]


def node_id(prefix: str, name: str) -> str:
    return f"{prefix}_{''.join(character if character.isalnum() else '_' for character in name)}"


def add_modules(lines: list[str], parent: str, prefix: str, names: list[str]) -> None:
    for name in names:
        identifier = node_id(prefix, name)
        lines.append(f'    {identifier}["{name}"]')
        lines.append(f"    {parent} --> {identifier}")


def generate() -> str:
    frontend_app = typescript_modules(ROOT / "frontend" / "app")
    frontend_components = typescript_modules(ROOT / "frontend" / "components")
    api_routes = python_modules(ROOT / "backend" / "app" / "api" / "routes")
    services = python_modules(ROOT / "backend" / "app" / "services")
    models = python_modules(ROOT / "backend" / "app" / "models")
    catalog_files = [path.name for path in sorted((ROOT / "data").glob("*")) if path.is_file()]
    lines = [
        "%% This file is generated by scripts/generate_architecture_diagram.py.",
        "%% Do not edit it by hand; change the repository structure and regenerate.",
        "flowchart LR",
        '    Browser["Browser"] --> Frontend["Next.js frontend"]',
        '    Frontend --> API["FastAPI API"]',
        '    API --> Catalog["Curated catalog"]',
        "",
        "    subgraph FrontendFiles[frontend/]",
        '        FrontendApp["app"]',
        '        FrontendComponents["components"]',
        "    end",
        "    Frontend --> FrontendApp",
        "    Frontend --> FrontendComponents",
    ]
    add_modules(lines, "FrontendApp", "frontend_app", frontend_app)
    add_modules(lines, "FrontendComponents", "frontend_component", frontend_components)
    lines.extend(["", "    subgraph BackendFiles[backend/app/]", '        Routes["api/routes"]', '        Services["services"]', '        Models["models"]', "    end", "    API --> Routes", "    Routes --> Services", "    Services --> Models"])
    add_modules(lines, "Routes", "route", api_routes)
    add_modules(lines, "Services", "service", services)
    add_modules(lines, "Models", "model", models)
    lines.extend(["", "    subgraph CatalogFiles[data/]", '        CatalogData["data"]', "    end", "    Catalog --> CatalogData"])
    add_modules(lines, "CatalogData", "catalog", catalog_files)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    diagram = generate()
    OUTPUT.write_text(diagram, encoding="utf-8")
    MARKDOWN_OUTPUT.write_text(
        "# Generated architecture diagram\n\n"
        "This structural view is generated from the repository layout. "
        "Do not edit it by hand; run "
        "`python3 scripts/generate_architecture_diagram.py` instead.\n\n"
        "```mermaid\n"
        f"{diagram}"
        "```\n",
        encoding="utf-8",
    )
